// Turns submission-script.js (the Devpost video's two-voice script) into files people use while recording:
//   node demo-video/script-tools.mjs   → demo-video/tandem-devpost.srt (captions for YouTube) + demo-video/SCRIPT.md
// Timings come from the same scene lengths the video uses, so captions and cues line up with tandem-devpost.mp4.
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'
import vm from 'node:vm'

const HERE = import.meta.dirname
export const WORDS_PER_SECOND = 2.4

export function loadScript() {
  const ctx = { window: {} }
  vm.runInNewContext(readFileSync(join(HERE, 'submission-script.js'), 'utf8'), ctx)
  return ctx.window.SUBMISSION_SCRIPT
}

const wordCount = (s) => s.trim().split(/\s+/).length

/** Absolute times: scenes get start/end, lines get start/end (end = estimated speaking time, never past the next line). */
export function timeline(script = loadScript()) {
  let acc = 0
  const scenes = script.scenes.map((s, i) => { const sc = { ...s, index: i + 1, start: acc, end: acc + s.dur }; acc += s.dur; return sc })
  const byId = Object.fromEntries(scenes.map((s) => [s.id, s]))
  const lines = script.lines.map((l) => ({ ...l, name: script.speakers[l.who], words: wordCount(l.text), start: byId[l.scene].start + l.at }))
    .sort((a, b) => a.start - b.start)
  lines.forEach((l, i) => {
    const next = lines[i + 1]?.start ?? acc
    l.end = Math.min(l.start + Math.max(1.2, l.words / WORDS_PER_SECOND), next - 0.15)
  })
  return { ...script, scenes, lines, duration: acc }
}

export const clock = (t, dec = 0) => { const m = Math.floor(t / 60), s = t - m * 60; return `${m}:${s.toFixed(dec).padStart(dec ? dec + 3 : 2, '0')}` }
const srtTime = (t) => { const ms = Math.round(t * 1000); const h = Math.floor(ms / 3600000), m = Math.floor(ms / 60000) % 60, s = Math.floor(ms / 1000) % 60; return `${String(h).padStart(2, '0')}:${String(m).padStart(2, '0')}:${String(s).padStart(2, '0')},${String(ms % 1000).padStart(3, '0')}` }

/** Captions: each spoken line split at sentence ends (max ~84 characters per cue), time shared by word count. */
export function toSrt(tl) {
  const cues = []
  for (const l of tl.lines) {
    const sentences = l.text.match(/[^.!?]+[.!?]+["”’]?\s*|[^.!?]+$/g).map((s) => s.trim())
    const chunks = []
    for (const s of sentences) {
      if (chunks.length && (chunks[chunks.length - 1] + ' ' + s).length <= 84) chunks[chunks.length - 1] += ' ' + s
      else chunks.push(s)
    }
    const total = chunks.reduce((n, c) => n + wordCount(c), 0)
    let t = l.start
    chunks.forEach((c, i) => {
      const d = ((l.end - l.start) * wordCount(c)) / total
      cues.push([t, t + d, (i === 0 ? `${l.name}: ` : '') + c])
      t += d
    })
  }
  return cues.map(([a, b, text], i) => `${i + 1}\n${srtTime(a)} --> ${srtTime(b)}\n${text}\n`).join('\n')
}

export function toMarkdown(tl) {
  const totals = Object.entries(tl.speakers).map(([k, name]) => {
    const ls = tl.lines.filter((l) => l.who === k)
    return `${name} ${ls.length} lines (~${Math.round(ls.reduce((n, l) => n + l.words, 0) / WORDS_PER_SECOND)} s)`
  }).join(' · ')
  let md = `# Tandem: Devpost demo video script\n\n`
  md += `Video: \`demo-video/tandem-devpost.mp4\` (${clock(tl.duration)}, silent; you talk over it). Captions: \`demo-video/tandem-devpost.srt\`.\n`
  md += `Start talking at the times below. The pace is about ${Math.round(WORDS_PER_SECOND * 60)} words a minute. If a line runs long, drop words rather than pauses, because the video won't wait.\n\n`
  md += `${totals}\n\n`
  for (const s of tl.scenes) {
    md += `## ${s.index}. ${s.title} (${clock(s.start)}–${clock(s.end)})\n\n_On screen: ${s.screen}_\n\n`
    for (const l of tl.lines.filter((x) => x.scene === s.id)) md += `- **${clock(l.start, 1)} ${l.name}:** ${l.text}\n`
    md += '\n'
  }
  md += `## Sources for the numbers\n\n` + tl.sources.map(([fact, src, url]) => `- ${fact}: ${src}, <${url}>`).join('\n') + '\n'
  md += `\n_Generated by \`node demo-video/script-tools.mjs\` from \`demo-video/submission-script.js\`._\n`
  return md
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const tl = timeline()
  writeFileSync(join(HERE, 'tandem-devpost.srt'), toSrt(tl))
  writeFileSync(join(HERE, 'SCRIPT.md'), toMarkdown(tl))
  console.log(`wrote tandem-devpost.srt + SCRIPT.md (${tl.lines.length} lines, ${clock(tl.duration)})`)
}
